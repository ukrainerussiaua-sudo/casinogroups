def norm(text: str) -> str:
    return " ".join(re.sub(r"[^\w\s]", " ", text.lower().replace("ё", "е")).split())


def parse(text: str, bot_username: str = ""):
    t = text.lower().replace("ё", "е").strip()
    if not t or len(t) > 80:
        return None
    bot = bot_username.lower()
    target = next((m for m in re.findall(r"@(\w+)", t) if m != bot), None)
    mentioned_bot = bool(bot) and f"@{bot}" in t
    slash = t.startswith("/")
    t = re.sub(r"@\w+", " ", t)
    key = norm(t)
    if not key:
        return None
    if slash:
        w = key.split()[0]
        if w in SLASH_GAME:
            return "game", SLASH_GAME[w]
        k = SLASH.get(w)
        if k == "profile":
            return "profile", {"username": target, "other": False}
        if k == "top":
            g = ALIAS.get(" ".join(key.split()[1:]))
            return "top", g
        return (k, None) if k else None
    m = GAME_RE.match(key)
    if m:
        return "game", ALIAS[m["g"]]
    m = TOP_GAME_RE.match(key)
    if m:
        return "top", ALIAS[m["g"]]
    if key in PROFILE:
        return "profile", {"username": target, "other": False}
    if key in PROFILE_OTHER:
        return "profile", {"username": target, "other": True}
    if key in TOP:
        return "top", None
    if key in RANKS:
        return "ranks", None
    if key in HELP:
        return "help", None
    return None
